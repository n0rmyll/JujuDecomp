import copy
import json
from pathlib import Path
import struct
import sys
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools'))
from check_source_link import (MANIFEST, global_definitions, original_function, replacement_plan,
                               verify_map_symbol, verify_owners, validate_manifest, split_text, verify_relocations)

ADDRESS, SIZE, SYMBOL, UNIT = 0x8020F9C8, 12, 'fn_8020F9C8', 'recovered/application_flag.c'
ENTRY = dict(address='0x8020F9C8', size=SIZE, symbol=SYMBOL, unit=UNIT)


def config():
    return dict(version='1.8.4', units=[
        dict(name='before', object='build/test-before.o', autogenerated=True, code_size=4, data_size=0),
        dict(name=UNIT, object='build/test-original.o', autogenerated=False, code_size=SIZE, data_size=0),
        dict(name='after', object='build/test-after.o', autogenerated=True, code_size=4, data_size=0)])


def elf_symbol(name=SYMBOL, binding=1, defined=True):
    strings = b'\0' + name.encode('ascii') + b'\0'
    symbols = bytes(16) + struct.pack('>IIIBBH', 1, 0, SIZE, binding << 4 | 2, 0, 3 if defined else 0)
    header = bytearray(52)
    header[:7] = b'\x7fELF\x01\x02\x01'
    struct.pack_into('>HH', header, 16, 1, 20)
    struct.pack_into('>I', header, 32, 52)
    struct.pack_into('>HH', header, 46, 40, 4)
    start = 52 + 4 * 40
    sections = [bytes(40), struct.pack('>10I', 0, 3, 0, 0, start, len(strings), 0, 0, 1, 0),
                struct.pack('>10I', 0, 2, 0, 0, start + len(strings), len(symbols), 1, 1, 4, 16),
                struct.pack('>10I', 0, 1, 6, 0, start + len(strings) + len(symbols), SIZE, 0, 0, 4, 0)]
    return bytes(header) + b''.join(sections) + strings + symbols + bytes(SIZE)


class SourceLinkTests(unittest.TestCase):
    def test_replacement_excludes_binary_target_and_preserves_order(self):
        compiled = ROOT / 'build/compiled_application_flag.o'
        objects, excluded = replacement_plan(config(), [ENTRY], {UNIT: compiled})
        self.assertEqual(objects, [ROOT / 'build/test-before.o', compiled, ROOT / 'build/test-after.o'])
        self.assertEqual(excluded, {UNIT: ROOT / 'build/test-original.o'})
        self.assertNotIn(excluded[UNIT], objects)

    def test_missing_duplicate_or_wrong_sized_source_units_fail(self):
        changes = []
        missing = config(); missing['units'].pop(1); changes.append(missing)
        duplicate = config(); duplicate['units'].append(copy.deepcopy(duplicate['units'][1])); changes.append(duplicate)
        for key, value in [('code_size', 16), ('data_size', 4), ('autogenerated', True)]:
            changed = config(); changed['units'][1][key] = value; changes.append(changed)
        for changed in changes:
            with self.subTest(config=changed), self.assertRaises(ValueError):
                replacement_plan(changed, [ENTRY], {UNIT: ROOT / 'build/compiled_application_flag.o'})

    def test_additional_source_and_duplicate_objects_fail(self):
        changed = config(); changed['units'][0]['autogenerated'] = False
        with self.assertRaisesRegex(ValueError, 'additional source'):
            replacement_plan(changed, [ENTRY], {UNIT: ROOT / 'build/compiled_application_flag.o'})
        changed = config(); changed['units'][2]['object'] = changed['units'][0]['object']
        with self.assertRaisesRegex(ValueError, 'Duplicate'):
            replacement_plan(changed, [ENTRY], {UNIT: ROOT / 'build/compiled_application_flag.o'})
        with self.assertRaisesRegex(ValueError, 'collision'):
            replacement_plan(config(), [ENTRY], {UNIT: ROOT / 'build/test-original.o'})

    def test_symbol_owner_requires_only_compiled_source(self):
        with tempfile.TemporaryDirectory() as directory:
            compiled, binary = [Path(directory) / name for name in ('compiled.o', 'binary.o')]
            compiled.write_bytes(elf_symbol()); binary.write_bytes(elf_symbol('other'))
            self.assertEqual(verify_owners([binary, compiled], [dict(ENTRY, relocations=[])], {UNIT: compiled})[SYMBOL], [compiled])
            binary.write_bytes(elf_symbol())
            with self.assertRaisesRegex(ValueError, 'exactly once'):
                verify_owners([binary, compiled], [dict(ENTRY, relocations=[])], {UNIT: compiled})
            compiled.write_bytes(elf_symbol(defined=False))
            with self.assertRaisesRegex(ValueError, 'compiled source'):
                verify_owners([compiled, binary], [dict(ENTRY, relocations=[])], {UNIT: compiled})

    def test_undefined_and_local_symbols_are_not_global_owners(self):
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory) / 'input.o'
            for content in (elf_symbol(defined=False), elf_symbol(binding=0)):
                path.write_bytes(content)
                self.assertEqual(global_definitions(path), [])
            path.write_bytes(b'bad ELF')
            with self.assertRaisesRegex(ValueError, 'ELF32'):
                global_definitions(path)
            path.write_bytes(elf_symbol()[:80])
            with self.assertRaisesRegex(ValueError, 'section table'):
                global_definitions(path)

    def test_map_requires_original_placement_size_and_compiled_object(self):
        line = '  0020a308 00000c 8020f9c8  4 fn_8020F9C8\tcompiled_application_flag.o\n'
        verify_map_symbol(line, SYMBOL, ADDRESS, SIZE, 'compiled_application_flag.o')
        for changed in (line.replace('8020f9c8', '8020f9cc'), line.replace('00000c', '000010'),
                        line.replace('compiled_application_flag.o', 'application_flag.o'), line + line):
            with self.subTest(map=changed), self.assertRaisesRegex(ValueError, 'Link map'):
                verify_map_symbol(changed, SYMBOL, ADDRESS, SIZE, 'compiled_application_flag.o')

    def test_original_function_must_be_in_verified_text_region(self):
        data = bytearray(0x110)
        struct.pack_into('>I', data, 0, 0x100)
        struct.pack_into('>I', data, 0x48, ADDRESS)
        struct.pack_into('>I', data, 0x90, SIZE)
        payload = b'test payload'
        data[0x100:0x10c] = payload
        self.assertEqual(original_function(data, ENTRY), payload)
        struct.pack_into('>I', data, 0x48, ADDRESS + 4)
        with self.assertRaisesRegex(ValueError, 'outside original text'):
            original_function(data, ENTRY)

    def test_multiple_units_preserve_link_order_and_exclude_both_originals(self):
        second = dict(address='0x801042FC', size=28, symbol='fn_801042FC', unit='matching/level_name.cpp')
        cfg = config()
        cfg['units'].insert(1, dict(name=second['unit'], object='build/test-level.o', autogenerated=False, code_size=28, data_size=0))
        compiled = {UNIT: ROOT / 'build/compiled_flag.o', second['unit']: ROOT / 'build/compiled_level.o'}
        objects, excluded = replacement_plan(cfg, [ENTRY, second], compiled)
        self.assertEqual(objects[1:3], [compiled[second['unit']], compiled[UNIT]])
        self.assertEqual(len(excluded), 2)
        self.assertFalse(set(excluded.values()) & set(objects))
        with self.assertRaisesRegex(ValueError, 'disagree'):
            replacement_plan(cfg, [ENTRY, second], {UNIT: compiled[UNIT]})

    def test_manifest_rejects_duplicates_overlaps_and_bad_ranges(self):
        manifest = json.loads(MANIFEST.read_text())
        self.assertEqual({e['id'] for e in validate_manifest(manifest)},
                         {'application_flag', 'level_name', 'application_iteration'})
        cases = []
        for key in ('id', 'unit', 'symbol', 'address'):
            changed = copy.deepcopy(manifest)
            changed['replacements'][1][key] = changed['replacements'][0][key]
            cases.append(changed)
        changed = copy.deepcopy(manifest)
        changed['replacements'][1]['address'] = '0x8020F9CC'
        changed['replacements'][1]['symbol'] = 'fn_8020F9CC'
        cases.append(changed)
        for size in (0, 3, -4, True, 0x100000000):
            changed = copy.deepcopy(manifest); changed['replacements'][0]['size'] = size; cases.append(changed)
        for changed in cases:
            with self.subTest(manifest=changed), self.assertRaises(ValueError):
                validate_manifest(changed)

    def test_manifest_rejects_unsupported_inputs_and_stale_relocation_contract(self):
        manifest = json.loads(MANIFEST.read_text())
        for key, value in [('source', '../escape.c'), ('unit', '/absolute.c'),
                           ('language', 'assembly'), ('symbol', 'wrong'), ('typo', 1)]:
            changed = copy.deepcopy(manifest); changed['replacements'][0][key] = value
            with self.subTest(key=key), self.assertRaises(ValueError):
                validate_manifest(changed)
        entry = manifest['replacements'][1]
        verify_relocations(copy.deepcopy(entry['relocations']), entry)
        for changed in ([], list(reversed(entry['relocations'])), [dict(entry['relocations'][0], type=5)]):
            with self.assertRaisesRegex(ValueError, 'relocations differ'):
                verify_relocations(changed, entry)

    def test_split_ranges_are_generated_from_manifest_only(self):
        manifest = json.loads(MANIFEST.read_text())
        text = split_text('Sections:\n\t.text type:code align:8\n', validate_manifest(manifest))
        self.assertIn('.text start:0x8020F9C8 end:0x8020F9D4 align:4', text)
        self.assertIn('.text start:0x801042FC end:0x80104318 align:4', text)
        self.assertIn('.text start:0x80213584 end:0x80213600 align:4', text)
        with self.assertRaisesRegex(ValueError, 'only a section header'):
            split_text(text, manifest['replacements'])

    def test_dependency_requires_one_owner_and_original_map_address(self):
        dependency = 'lbl_802CD918'
        with tempfile.TemporaryDirectory() as directory:
            compiled, binary = [Path(directory) / name for name in ('compiled.o', 'binary.o')]
            compiled.write_bytes(elf_symbol()); binary.write_bytes(elf_symbol('other'))
            entry = dict(ENTRY, relocations=[dict(symbol=dependency)])
            with self.assertRaisesRegex(ValueError, 'dependency requires'):
                verify_owners([compiled, binary], [entry], {UNIT: compiled})
            binary.write_bytes(elf_symbol(dependency))
            verify_owners([compiled, binary], [entry], {UNIT: compiled})
        line = '  0001fd78 000744 802cd918  8 lbl_802CD918\tauto_data.o\n'
        verify_map_symbol(line, dependency, 0x802CD918, object_name='auto_data.o')
        with self.assertRaisesRegex(ValueError, 'placement differs'):
            verify_map_symbol(line, dependency, 0x802CD91C, object_name='auto_data.o')

    def test_source_to_source_call_dependency_resolves_to_compiled_callee(self):
        caller = dict(address='0x80213584', size=124, symbol='fn_80213584',
                      unit='matching/application_iteration.cpp', relocations=[dict(symbol=SYMBOL)])
        callee = dict(ENTRY, relocations=[])
        with tempfile.TemporaryDirectory() as directory:
            caller_obj = Path(directory) / 'compiled_iteration.o'
            callee_obj = Path(directory) / 'compiled_flag.o'
            caller_obj.write_bytes(elf_symbol(caller['symbol']))
            callee_obj.write_bytes(elf_symbol())
            compiled = {caller['unit']: caller_obj, UNIT: callee_obj}
            definitions = verify_owners([caller_obj, callee_obj], [caller, callee], compiled)
            self.assertEqual(definitions[caller['relocations'][0]['symbol']], [callee_obj])
            wrong_owner = Path(directory) / 'binary_flag.o'
            wrong_owner.write_bytes(elf_symbol())
            with self.assertRaisesRegex(ValueError, 'compiled source'):
                verify_owners([caller_obj, wrong_owner], [caller, callee], compiled)

    def test_direct_call_and_small_data_contract_changes_are_rejected(self):
        entries = validate_manifest(json.loads(MANIFEST.read_text()))
        entry = next(e for e in entries if e['id'] == 'application_iteration')
        verify_relocations(copy.deepcopy(entry['relocations']), entry)
        for index in range(len(entry['relocations'])):
            changed = copy.deepcopy(entry['relocations'])
            changed[index]['target'] = '0x80001000'
            with self.subTest(relocation=index), self.assertRaisesRegex(ValueError, 'relocations differ'):
                verify_relocations(changed, entry)

    def test_cpp_exception_setting_is_explicit_and_only_allowed_for_cpp(self):
        manifest = json.loads(MANIFEST.read_text())
        entry = next(e for e in manifest['replacements'] if e['id'] == 'application_iteration')
        self.assertIs(entry['cpp_exceptions'], False)
        validate_manifest(manifest)
        for language, setting in [('c++', 'off'), ('c++', 0), ('c', False)]:
            changed = copy.deepcopy(manifest)
            changed['replacements'][-1]['language'] = language
            changed['replacements'][-1]['cpp_exceptions'] = setting
            with self.subTest(language=language, setting=setting), self.assertRaisesRegex(ValueError, 'exception setting'):
                validate_manifest(changed)


if __name__ == '__main__':
    unittest.main()
