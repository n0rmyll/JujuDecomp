#!/usr/bin/env python3
"""Recognize and compile complete 52-byte caller shapes; compare all bytes.

The C/C++ types are provisional interface candidates, not original declarations.
No opcode substitutions, masks, or explicit register/stack harness is used.
"""
import argparse
import collections
import hashlib
import json
from pathlib import Path
import re
import subprocess

from check_new_matching import original_bytes
from integer_recovery import render as render_models
from ppc_leaf import load_functions
from ppc_matching import function_code

ROOT = Path(__file__).resolve().parents[1]
SOURCE = 'src/matching/caller_patterns_next.cpp'
PROLOGUE = [
    'm->w32((r1 + UINT32_C(0xfffffff0)), (uint32_t)r1);',
    'r1 = (r1 + UINT32_C(0xfffffff0));', 'r0 = lr;',
    'm->w32((r1 + UINT32_C(0x14)), (uint32_t)r0);']
EPILOGUE = ['r0 = m->r32((r1 + UINT32_C(0x14)));', 'lr = r0;',
            'r1 = r1 + UINT32_C(0x10);', 'return r3;']
SAVE = ['m->w32((r1 + UINT32_C(0xc)), (uint32_t)r31);', 'r31 = r3;']
RESTORE = [EPILOGUE[0], 'r31 = m->r32((r1 + UINT32_C(0xc)));'] + EPILOGUE[1:]


def call(pc, delta, target):
    return [f'uint32_t call_target_{pc+delta:08X} = UINT32_C({target});',
            f'lr = UINT32_C({hex(pc+delta+4)});', f'TAK_OPAQUE_CALL(call_target_{pc+delta:08X});']


def templates(address):
    pc = int(address, 0)
    return {
        'two_calls': PROLOGUE + SAVE + call(pc, 20, '@target') + ['r3 = r31;'] + call(pc, 28, '@target2') + RESTORE,
        'clear_guard': PROLOGUE + [
            'r0 = m->r8((r3 + UINT32_C(@offset)));', 'cr0 = cmp_unsigned(r0, UINT32_C(0x0));',
            f'if ((cr0 & 4u)) goto block_{pc+36:08X};', 'r0 = UINT32_C(0x0);',
            'm->w8((r3 + UINT32_C(@offset)), (uint8_t)r0);'] + call(pc, 32, '@target') + [f'block_{pc+36:08X}: ;'] + EPILOGUE,
        'store_result': PROLOGUE + SAVE + call(pc, 20, '@target') + [
            'r4 = m->r32((r31 + UINT32_C(@offset)));',
            'm->w32((r4 + UINT32_C(@field)), (uint32_t)r3);'] + RESTORE,
        'init_pointer': PROLOGUE + SAVE + call(pc, 20, '@target') + [
            'r0 = r31 + UINT32_C(@offset);',
            'm->w32((r31 + UINT32_C(@field)), (uint32_t)r0);'] + RESTORE,
        'null_delegate': PROLOGUE + ['r3 = m->r32((r3 + UINT32_C(@offset)));',
            'cr0 = cmp_unsigned(r3, UINT32_C(0x0));', f'if ((cr0 & 4u)) goto block_{pc+32:08X};'] + call(pc, 24, '@target') + [
            f'goto block_{pc+36:08X};', f'block_{pc+32:08X}: ;',
            'r3 = UINT32_C(0x0);', f'block_{pc+36:08X}: ;'] + EPILOGUE,
        'sentinel': PROLOGUE + ['r3 = m->r32((r13 + UINT32_C(@sda)));',
            'cr0 = cmp_signed(r3, UINT32_C(@value));', f'if ((cr0 & 4u)) goto block_{pc+36:08X};'] + call(pc, 24, '@target') + [
            'r0 = UINT32_C(@value);', 'm->w32((r13 + UINT32_C(@sda)), (uint32_t)r0);',
            f'block_{pc+36:08X}: ;'] + EPILOGUE,
        'clear_subobject': PROLOGUE + ['r0 = UINT32_C(0x0);',
            'r4 = m->r32((r3 + UINT32_C(@offset)));',
            'm->w8((r4 + UINT32_C(@field)), (uint8_t)r0);',
            'r3 = m->r32((r3 + UINT32_C(@offset)));',
            'r3 = r3 + UINT32_C(@subobject);'] + call(pc, 32, '@target') + EPILOGUE,
    }


def recover(specs):
    result = []
    for spec in specs:
        if spec['original_bytes'] != 52:
            continue
        body = '\n'.join(line for line in spec['body'][84:] if line != 'TAK_INTEGER_STEP();')
        for kind, template in templates(spec['address']).items():
            tokens = re.split(r'(@\w+)', '\n'.join(template))
            seen = set()
            pattern = ''
            for token in tokens:
                if token.startswith('@'):
                    name = token[1:]
                    pattern += f'(?P={name})' if name in seen else f'(?P<{name}>0x[0-9a-f]+)'
                    seen.add(name)
                else:
                    pattern += re.escape(token)
            match = re.fullmatch(pattern, body)
            if match:
                values = {key: int(value, 0) for key, value in match.groupdict().items()}
                if kind == 'sentinel':
                    # Address translation uses the revision-checked r13 base.
                    values['global'] = (0x80338280 + (values['sda'] - 0x100000000 if values['sda'] & 0x80000000 else values['sda'])) & 0xffffffff
                result.append(dict(address=spec['address'], kind=kind, **values))
                break
    return result


def render(entries):
    out = ['/* Generated by tools/caller_patterns_next.py --write-source.',
           ' * Complete recognized caller shapes; source types remain provisional. */',
           'typedef unsigned char u8;', 'typedef unsigned int u32;', 'extern "C" {']
    for entry in entries:
        address = entry['address']
        kind = entry['kind']
        target = f'fn_{entry["target"]:08X}'
        off = hex(entry.get('offset', 0)); field = hex(entry.get('field', 0))
        out += [f'#if TAK_FN == {address}']
        if kind == 'two_calls':
            second = f'fn_{entry["target2"]:08X}'
            out += [f'extern void {target}(void *), {second}(void *);',
                    f'void fn_{address[2:]}(void *self) {{ {target}(self); {second}(self); }}']
        elif kind == 'clear_guard':
            out += [f'extern void {target}(void *);', f'void fn_{address[2:]}(void *self) {{',
                    f'    if (*(u8 *)((u8 *)self + {off})) {{',
                    f'        *(u8 *)((u8 *)self + {off}) = 0;', f'        {target}(self);', '    }', '}']
        elif kind == 'store_result':
            out += [f'extern u32 {target}(void *);', f'void fn_{address[2:]}(void *self) {{',
                    f'    *(u32 *)(*(u8 **)((u8 *)self + {off}) + {field}) = {target}(self);', '}']
        elif kind == 'init_pointer':
            out += [f'extern void {target}(void *);', f'void fn_{address[2:]}(void *self) {{',
                    f'    {target}(self);', f'    *(void **)((u8 *)self + {field}) = (u8 *)self + {off};', '}']
        elif kind == 'null_delegate':
            out += [f'extern u32 {target}(void *);', f'u32 fn_{address[2:]}(void *self) {{',
                    f'    void *object = *(void **)((u8 *)self + {off});', f'    return object ? {target}(object) : 0;', '}']
        elif kind == 'sentinel':
            label = f'lbl_{entry["global"]:08X}'
            signed = entry['value'] - 0x100000000 if entry['value'] & 0x80000000 else entry['value']
            out += [f'extern int {label};', f'extern void {target}(int);', f'void fn_{address[2:]}() {{',
                    f'    if ({label} != {signed}) {{ {target}({label}); {label} = {signed}; }}', '}']
        elif kind == 'clear_subobject':
            out += [f'extern void {target}(void *);', f'void fn_{address[2:]}(void *self) {{',
                    f'    *(u8 *)(*(u8 **)((u8 *)self + {off}) + {field}) = 0;',
                    f'    {target}(*(u8 **)((u8 *)self + {off}) + {hex(entry["subobject"])});', '}']
        else:
            raise ValueError('Unknown caller shape: ' + kind)
        out += ['#endif']
    return '\n'.join(out + ['}', ''])


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write-source', action='store_true')
    args = parser.parse_args()
    specs = json.loads((ROOT / 'analysis/call-helper-specs.json').read_text())['routines']
    if render_models(specs, full_context=True, allow_calls=True) != (ROOT / 'src/recovered/call_leaf_helpers.c').read_text():
        raise ValueError('Caller models differ from saved specifications')
    entries = recover(specs)
    if not entries:
        raise ValueError('No recognized caller patterns')
    source = render(entries)
    if args.write_source:
        (ROOT / SOURCE).write_text(source)
    elif (ROOT / SOURCE).read_text() != source:
        raise ValueError('Candidate source differs; regenerate explicitly')
    manifest = json.loads((ROOT / 'analysis/semantic-functions.json').read_text())
    inventory = {r['address']: r for r in manifest['routines']}
    words = load_functions([r['address'][2:] for r in entries])
    output = ROOT / 'build/agent-caller-patterns'; output.mkdir(parents=True, exist_ok=True)
    (output / 'report.json').unlink(missing_ok=True)
    cc = ROOT / 'tools/mwcc/GC/1.3.2/mwcceppc.exe'; runner = ROOT / 'tools/wibo'
    results = []
    for entry in entries:
        address = entry['address']; name = 'fn_' + address[2:]; model = inventory[address]
        src = output / (name + '.cpp'); obj = output / (name + '.o')
        for suffix in ('.o', '.bin', '.original.bin', '.diff.txt'):
            (output / (name + suffix)).unlink(missing_ok=True)
        src.write_text('#define TAK_FN ' + address + '\n' + source)
        command = [str(runner), str(cc), '-c', '-lang', 'c++', '-proc', 'gekko', '-O4,p', '-nodefaults', str(src), '-o', str(obj)]
        run = subprocess.run(command, capture_output=True, text=True)
        (output / (name + '.log')).write_text(run.stdout + run.stderr)
        record = dict(address=address, function=name, model_source=model['source'], model_symbol=model['symbol'],
                      original_size=model['original_bytes'], interface=entry, candidate_sha256=digest(src),
                      command=command, exact_match=False)
        if run.returncode:
            record.update(status='compile_error', error=run.stdout + run.stderr)
        else:
            record['object_sha256'] = digest(obj)
            try:
                code, relocations = function_code(obj, name, int(address, 0), {})
                expected = original_bytes(words[address[2:]])
                if len(expected) != model['original_bytes']:
                    raise ValueError('Inventory size differs from verified original')
                (output / (name + '.bin')).write_bytes(code); (output / (name + '.original.bin')).write_bytes(expected)
                diffs = [f'+0x{i:04x}: original {expected[i:i+4].hex() or "<end>"} candidate {code[i:i+4].hex() or "<end>"}'
                         for i in range(0, max(len(code), len(expected)), 4) if code[i:i+4] != expected[i:i+4]]
                (output / (name + '.diff.txt')).write_text('\n'.join(diffs))
                record.update(status='match' if code == expected else 'different', exact_match=code == expected,
                              candidate_size=len(code), relocations=relocations)
            except (ValueError, IndexError) as error:
                record.update(status='relocation_error', error=str(error))
        results.append(record)
    sources = [SOURCE, 'src/recovered/call_leaf_helpers.c', 'analysis/call-helper-specs.json',
               'tools/caller_patterns_next.py', 'tools/integer_recovery.py']
    report = dict(family='caller-patterns-next', dol_sha256=manifest['dol_sha256'],
                  scope='Full relocated individual function code; provisional compiler-managed C interfaces',
                  compiler_sha256=digest(cc), runner_sha256=digest(runner), model_hashes={p: digest(ROOT / p) for p in sources},
                  candidate_interface='Complete recognized 52-byte two-call, guarded-clear, result-store, pointer-init, null-delegate, sentinel and subobject wrappers',
                  checked=len(results), matched=sum(r['exact_match'] for r in results),
                  matched_bytes=sum(r['original_size'] for r in results if r['exact_match']), results=results)
    (output / 'report.json').write_text(json.dumps(report, indent=2) + '\n')
    print(f'{report["matched"]}/{len(results)} exact matches / {report["matched_bytes"]} bytes; '
          f'{dict(collections.Counter(r["status"] for r in results))}')
    if any(r['status'].endswith('_error') for r in results):
        raise SystemExit(1)


if __name__ == '__main__':
    main()
