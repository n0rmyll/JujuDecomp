#!/usr/bin/env python3
"""Link one recovered C unit with binary fallbacks; require exact full DOL equality."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import struct

from check_application_flag import EXPECTED_HASH
from check_rebuild_foundation import compare_dols, dol_layout, run_logged
from ppc_matching import function_code

ROOT = Path(__file__).resolve().parents[1]
ADDRESS = 0x8020F9C8
SIZE = 12
SYMBOL = 'fn_8020F9C8'
UNIT = 'recovered/application_flag.c'
SOURCE = ROOT / 'src/recovered/application_flag.c'
SPLITS = ROOT / 'analysis/source-link-splits.txt'


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def display(path):
    return str(path.relative_to(ROOT)) if path.is_relative_to(ROOT) else str(path)


def original_function(data):
    for section in dol_layout(data)['sections']:
        start = int(section['address'], 0)
        if section['kind'] == 'text' and start <= ADDRESS and ADDRESS + SIZE <= start + section['size']:
            offset = section['offset'] + ADDRESS - start
            return data[offset:offset + SIZE]
    raise ValueError('Source replacement is outside original text')


def replacement_plan(config, compiled):
    """Select exactly one bounded source unit; no duplicate original code in link."""
    if config.get('version') != '1.8.4' or config.get('modules') or config.get('links'):
        raise ValueError('Unsupported split configuration')
    units = config['units']
    selected = [u for u in units if u['name'] == UNIT]
    if len(selected) != 1:
        raise ValueError('Expected exactly one recovered-source unit')
    target = selected[0]
    if target.get('autogenerated') is not False or target['code_size'] != SIZE or target['data_size'] != 0:
        raise ValueError('Unexpected source-unit ownership or size')
    if any(not u.get('autogenerated') for u in units if u is not target):
        raise ValueError('Unexpected additional source unit')
    objects = [Path(u['object']) if Path(u['object']).is_absolute() else ROOT / u['object'] for u in units]
    original = objects[units.index(target)]
    if len(set(objects)) != len(objects) or compiled in objects:
        raise ValueError('Duplicate split object or compiled-object collision')
    objects[units.index(target)] = compiled
    if original in objects or objects.count(compiled) != 1:
        raise ValueError('Original target object was not replaced exactly once')
    return objects, original


def global_definitions(path):
    """Read defined GLOBAL/WEAK names from strict ELF32 big-endian PPC inputs."""
    data = path.read_bytes()
    if len(data) < 52 or data[:7] != b'\x7fELF\x01\x02\x01' or struct.unpack_from('>HH', data, 16) != (1, 20):
        raise ValueError('Expected relocatable ELF32/PPC input')
    start = struct.unpack_from('>I', data, 32)[0]
    stride, count = struct.unpack_from('>HH', data, 46)
    if stride != 40 or not count or start + count * stride > len(data):
        raise ValueError('Invalid ELF section table')
    sections = [struct.unpack_from('>10I', data, start + i * stride) for i in range(count)]
    def contents(section):
        offset, size = section[4:6]
        if offset + size > len(data):
            raise ValueError('Truncated ELF section')
        return data[offset:offset + size]
    names = []
    for section in sections:
        if section[1] != 2:
            continue
        if section[9] != 16 or section[5] % 16 or section[6] >= len(sections):
            raise ValueError('Invalid ELF symbol table')
        strings = contents(sections[section[6]])
        symbols = contents(section)
        for offset in range(0, len(symbols), 16):
            name, _, _, info, _, index = struct.unpack_from('>IIIBBH', symbols, offset)
            if info >> 4 not in (1, 2) or index == 0:
                continue
            if name >= len(strings) or b'\0' not in strings[name:]:
                raise ValueError('Invalid ELF symbol name')
            names.append(strings[name:].split(b'\0', 1)[0].decode('ascii'))
    return names


def verify_source_owner(objects, compiled):
    owners = [path for path in objects for name in global_definitions(path) if name == SYMBOL]
    if owners != [compiled]:
        raise ValueError('Target symbol must be defined exactly once by compiled source')
    return owners


def verify_map(text):
    matches = re.findall(r'^\s*[0-9a-fA-F]{8}\s+00000c\s+8020f9c8\s+\d+\s+fn_8020F9C8\s+compiled_application_flag\.o\s*$', text, re.M)
    if len(matches) != 1:
        raise ValueError('Link map does not place the source function at its original address')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT / 'build/source-link')
    args = parser.parse_args()
    output = args.output.resolve()
    output.mkdir(parents=True, exist_ok=True)
    report_path = output / 'report.json'
    report_path.unlink(missing_ok=True)
    original = (ROOT / 'analysis/main.dol').read_bytes()
    if hashlib.sha256(original).hexdigest() != EXPECTED_HASH:
        raise ValueError('Unexpected DOL revision')
    expected = original_function(original)
    source_hash = digest(SOURCE)
    commands = []
    def execute(command, log):
        commands.append(command)
        run_logged(command, output / log)
    # Exhaustive existing behavior test, without changing the isolated-match report.
    host = output / 'behavior-test'
    execute(['clang', '-std=c11', '-Wall', '-Wextra', '-Werror', '-O2', str(SOURCE),
             str(ROOT / 'tests/application_flag.c'), '-o', str(host)], 'host-compile.log')
    execute([str(host)], 'behavior.log')
    local_splits = output / 'splits.txt'
    local_splits.write_bytes(SPLITS.read_bytes())
    config_path = output / 'config.yml'
    config_path.write_text(json.dumps(dict(object=str(ROOT / 'analysis/main.dol'),
        hash=hashlib.sha1(original).hexdigest(), splits=str(local_splits)), indent=2) + '\n')
    dtk = ROOT / 'tools/dtk'
    execute([str(dtk), 'dol', 'split', str(config_path), str(output / 'split')], 'split.log')
    split_config_path = output / 'split/config.json'
    config = json.loads(split_config_path.read_text())
    runner = ROOT / 'tools/wibo'
    cc = ROOT / 'tools/mwcc/GC/1.3.2/mwcceppc.exe'
    linker = ROOT / 'tools/mwcc/GC/1.3.2/mwldeppc.exe'
    compiled = output / 'compiled_application_flag.o'
    compiled.unlink(missing_ok=True)
    execute([str(runner), str(cc), '-c', '-lang', 'c', '-proc', 'gekko', '-O4,p',
             '-fp', 'hardware', '-nodefaults', '-Dtak_application_request_stop=' + SYMBOL,
             str(SOURCE), '-o', str(compiled)], 'compile.log')
    code, relocations = function_code(compiled, SYMBOL, ADDRESS, {})
    if code != expected or relocations:
        raise ValueError('Compiled source does not exactly match the original function')
    objects, excluded = replacement_plan(config, compiled)
    old_code, _ = function_code(excluded, SYMBOL, ADDRESS, {})
    if old_code != expected:
        raise ValueError('Extracted target unit differs from original function')
    verify_source_owner(objects, compiled)
    hashes = {display(p): digest(p) for p in objects}
    elf, dol, map_path = [output / ('source.' + extension) for extension in ('elf', 'dol', 'map')]
    for path in (elf, dol, map_path):
        path.unlink(missing_ok=True)
    lcf = Path(config['ldscript'])
    if not lcf.is_absolute():
        lcf = ROOT / lcf
    execute([str(runner), str(linker), '-nodefaults', '-fp', 'hardware', '-lcf', str(lcf),
             '-m', config['entry'], '-o', str(elf), '-map', str(map_path),
             *[str(p) for p in objects]], 'link.log')
    execute([str(dtk), 'elf2dol', str(elf), str(dol)], 'elf2dol.log')
    layout = compare_dols(original, dol.read_bytes())
    verify_map(map_path.read_text())
    if digest(SOURCE) != source_hash or any(digest(path) != hashes[display(path)] for path in objects):
        raise ValueError('Source or link input changed during the build')
    report = dict(revision='GJUE78 rev 0', exact_match=True,
        scope='One recovered C function linked with binary-derived fallbacks; no gameplay test',
        source_replacements=1, linked_source_functions=1, linked_source_bytes=SIZE,
        replacement=dict(address=f'0x{ADDRESS:08X}', size=SIZE, symbol=SYMBOL,
            source=display(SOURCE), source_sha256=source_hash, object=display(compiled),
            object_sha256=digest(compiled), excluded_binary_object=display(excluded),
            excluded_binary_sha256=digest(excluded), original_unit=UNIT,
            symbol_owner=display(compiled), code_sha256=hashlib.sha256(code).hexdigest()),
        object_count=len(objects), binary_derived_objects=len(objects)-1,
        original_sha256=EXPECTED_HASH, rebuilt_sha256=digest(dol), rebuilt_size=dol.stat().st_size,
        elf_sha256=digest(elf), map_sha256=digest(map_path),
        source_split_template_sha256=digest(SPLITS), split_config_sha256=digest(split_config_path),
        split_input_sha256=digest(config_path), split_file_sha256=digest(local_splits),
        lcf_sha256=digest(lcf), checker_sha256=digest(Path(__file__).resolve()),
        helper_hashes={display(p):digest(p) for p in (ROOT / 'tools/check_rebuild_foundation.py',
            ROOT / 'tools/ppc_matching.py', ROOT / 'tests/application_flag.c')},
        tools={display(p):digest(p) for p in (runner, cc, linker, dtk)},
        object_hashes=hashes, commands=commands, **layout)
    report_path.write_text(json.dumps(report, indent=2) + '\n')
    print(f'PASS: one recovered C function / {SIZE} bytes + {len(objects)-1} binary-derived objects; '
          f'exact {len(original):,}-byte DOL; SHA-256 {EXPECTED_HASH}')
    print(report_path)


if __name__ == '__main__':
    main()
