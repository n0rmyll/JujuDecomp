#!/usr/bin/env python3
"""Recover narrowly recognized 48-byte caller source forms and verify full code.

Types are provisional; compiler-managed frames and unchanged -O4,p settings.
No instruction substitution or masked comparisons are used.
"""
import argparse
import collections
import hashlib
import json
from pathlib import Path
import re
import subprocess

from check_new_matching import original_bytes
from integer_recovery import render as render_models
from ppc_leaf import load_functions
from ppc_matching import function_code

ROOT = Path(__file__).resolve().parents[1]
SOURCE = 'src/matching/caller_compiler_fixes.cpp'
PROLOGUE = ['m->w32((r1 + UINT32_C(0xfffffff0)), (uint32_t)r1);',
            'r1 = (r1 + UINT32_C(0xfffffff0));', 'r0 = lr;',
            'm->w32((r1 + UINT32_C(0x14)), (uint32_t)r0);']
EPILOGUE = ['r0 = m->r32((r1 + UINT32_C(0x14)));', 'lr = r0;',
            'r1 = r1 + UINT32_C(0x10);', 'return r3;']


def expected_body(entry):
    pc = int(entry['address'], 0)
    kind = entry['kind']
    call_pc = pc + (12 if kind == 'result_flags' else 28)
    call = [f'uint32_t call_target_{call_pc:08X} = UINT32_C({hex(entry["target"])});',
            f'lr = UINT32_C({hex(call_pc+4)});', f'TAK_OPAQUE_CALL(call_target_{call_pc:08X});']
    if kind == 'embedded_guard':
        middle = [f'r0 = m->r32((r3 + UINT32_C({hex(entry["offset"])})));',
                  'cr0 = cmp_unsigned(r0, UINT32_C(0x0));',
                  f'if ((cr0 & 4u)) goto block_{pc+32:08X};',
                  f'r3 = r3 + UINT32_C({hex(entry["offset"])});'] + call + [f'block_{pc+32:08X}: ;']
    elif kind == 'switch_guard':
        middle = [f'r0 = m->r32((r3 + UINT32_C({hex(entry["offset"])})));',
                  f'cr0 = cmp_signed(r0, UINT32_C({hex(entry["case"])}));',
                  f'if ((cr0 & 4u)) goto block_{pc+28:08X};',
                  f'goto block_{pc+32:08X};', f'block_{pc+28:08X}: ;'] + call + [f'block_{pc+32:08X}: ;']
    elif kind == 'swap_zero':
        return PROLOGUE[:3] + ['r5 = UINT32_C(0x0);'] + PROLOGUE[3:] + [
            'r0 = r3;', 'r3 = r4;', 'r4 = r0;'] + call + EPILOGUE
    elif kind == 'result_flags':
        middle = call + ['r4 = UINT32_C(0x0);', 'r0 = UINT32_C(0x1);',
                         f'm->w8((r3 + UINT32_C({hex(entry["zero_offset"])})), (uint8_t)r4);',
                         f'm->w8((r3 + UINT32_C({hex(entry["one_offset"])})), (uint8_t)r0);']
    else:
        raise ValueError('Unknown compiler-fix shape: ' + kind)
    return PROLOGUE + middle + EPILOGUE


def recover(specs):
    result = []
    for spec in specs:
        if spec['original_bytes'] != 48:
            continue
        body = [line for line in spec['body'][84:] if line != 'TAK_INTEGER_STEP();']
        text = '\n'.join(body)
        target = re.search(r'call_target_[0-9A-F]+ = UINT32_C\((0x[0-9a-f]+)\);', text)
        if not target:
            continue
        common = dict(address=spec['address'], target=int(target[1], 0))
        candidates = [dict(common, kind='swap_zero')]
        field = re.search(r'r0 = m->r32\(\(r3 \+ UINT32_C\((0x[0-9a-f]+)\)\)\);', text)
        if field and 0 < int(field[1], 0) <= 0x7fff:
            offset = int(field[1], 0)
            candidates.append(dict(common, kind='embedded_guard', offset=offset))
            case = re.search(r'cr0 = cmp_signed\(r0, UINT32_C\((0x[0-9a-f]+)\)\);', text)
            if case:
                candidates.append(dict(common, kind='switch_guard', offset=offset, case=int(case[1], 0)))
        zero = re.search(r'm->w8\(\(r3 \+ UINT32_C\((0x[0-9a-f]+)\)\), \(uint8_t\)r4\);', text)
        one = re.search(r'm->w8\(\(r3 \+ UINT32_C\((0x[0-9a-f]+)\)\), \(uint8_t\)r0\);', text)
        if zero and one and int(one[1], 0) + 1 == int(zero[1], 0) and int(one[1], 0) > 0:
            candidates.append(dict(common, kind='result_flags', zero_offset=int(zero[1], 0), one_offset=int(one[1], 0)))
        match = next((entry for entry in candidates if body == expected_body(entry)), None)
        if match:
            result.append(match)
    return result


def render(entries):
    out = ['/* GJUE78 rev 0 narrowly recognized caller candidates.',
           ' * Generated by tools/caller_compiler_fixes.py --write-source.',
           ' * Types provisional; full relocated instruction equality is required. */',
           'typedef unsigned char u8;', 'typedef unsigned int u32;', 'typedef signed int s32;',
           'extern "C" {']
    for entry in entries:
        address, target, kind = entry['address'], entry['target'], entry['kind']
        out += [f'#if TAK_FN == {address}']
        if kind == 'embedded_guard':
            out += ['struct Embedded { u32 value; };',
                    f'struct Object {{ u8 pad[{hex(entry["offset"])}]; Embedded sub; }};',
                    f'extern void fn_{target:08X}(Embedded *);',
                    f'void fn_{address[2:]}(Object *self) {{',
                    f'    if (self->sub.value) fn_{target:08X}(&self->sub);', '}']
        elif kind == 'switch_guard':
            case = entry['case'] if entry['case'] < 0x80000000 else entry['case'] - 0x100000000
            out += [f'struct Object {{ u8 pad[{hex(entry["offset"])}]; s32 value; }};',
                    f'extern void fn_{target:08X}(Object *);',
                    f'void fn_{address[2:]}(Object *self) {{', '    switch (self->value) {',
                    f'    case {case}: fn_{target:08X}(self); break;', '    default: break;', '    }', '}']
        elif kind == 'swap_zero':
            out += [f'extern void fn_{target:08X}(void *, void *, u32);',
                    f'void fn_{address[2:]}(void *first, void *second) {{',
                    f'    fn_{target:08X}(second, first, 0);', '}']
        elif kind == 'result_flags':
            out += [f'struct Object {{ u8 pad[{hex(entry["one_offset"])}]; u8 one, zero; }};',
                    f'extern Object *fn_{target:08X}(void *);',
                    f'void fn_{address[2:]}(void *self) {{', f'    Object *result = fn_{target:08X}(self);',
                    '    result->zero = 0;', '    result->one = 1;', '}']
        else:
            raise ValueError('Unknown compiler-fix shape: ' + kind)
        out += ['#endif']
    return '\n'.join(out + ['}', ''])


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write-source', action='store_true')
    args = parser.parse_args()
    specs = json.loads((ROOT / 'analysis/call-helper-specs.json').read_text())['routines']
    if render_models(specs, full_context=True, allow_calls=True) != (ROOT / 'src/recovered/call_leaf_helpers.c').read_text():
        raise ValueError('Caller models differ from saved specifications')
    entries = recover(specs)
    if not entries:
        raise ValueError('No recognized compiler-fix shapes')
    source = render(entries)
    if args.write_source:
        (ROOT / SOURCE).write_text(source)
    elif (ROOT / SOURCE).read_text() != source:
        raise ValueError('Compiler-fix source differs; regenerate explicitly')
    manifest = json.loads((ROOT / 'analysis/semantic-functions.json').read_text())
    inventory = {x['address']: x for x in manifest['routines']}
    words = load_functions([x['address'][2:] for x in entries])
    output = ROOT / 'build/agent-compiler-fixes'
    output.mkdir(parents=True, exist_ok=True)
    (output / 'report.json').unlink(missing_ok=True)
    cc = ROOT / 'tools/mwcc/GC/1.3.2/mwcceppc.exe'
    runner = ROOT / 'tools/wibo'
    results = []
    for entry in entries:
        address = entry['address']; model = inventory[address]; name = 'fn_' + address[2:]
        src = output / (name + '.cpp'); obj = output / (name + '.o')
        for suffix in ('.o', '.bin', '.original.bin', '.diff.txt'):
            (output / (name + suffix)).unlink(missing_ok=True)
        src.write_text('#define TAK_FN ' + address + '\n' + source)
        command = [str(runner), str(cc), '-c', '-lang', 'c++', '-proc', 'gekko',
                   '-O4,p', '-nodefaults', str(src), '-o', str(obj)]
        run = subprocess.run(command, capture_output=True, text=True)
        (output / (name + '.log')).write_text(run.stdout + run.stderr)
        record = dict(address=address, function=name, model_source=model['source'],
                      model_symbol=model['symbol'], original_size=model['original_bytes'],
                      interface=entry, candidate_sha256=digest(src), command=command, exact_match=False)
        if run.returncode:
            record.update(status='compile_error', error=run.stdout + run.stderr)
        else:
            record['object_sha256'] = digest(obj)
            try:
                code, relocations = function_code(obj, name, int(address, 0), {})
                expected = original_bytes(words[address[2:]])
                if len(expected) != model['original_bytes']:
                    raise ValueError('Inventory size differs from verified original')
                (output / (name + '.bin')).write_bytes(code)
                (output / (name + '.original.bin')).write_bytes(expected)
                diffs = [f'+0x{i:04x}: original {expected[i:i+4].hex() or "<end>"} candidate {code[i:i+4].hex() or "<end>"}'
                         for i in range(0, max(len(code), len(expected)), 4) if code[i:i+4] != expected[i:i+4]]
                (output / (name + '.diff.txt')).write_text('\n'.join(diffs))
                record.update(status='match' if code == expected else 'different',
                              exact_match=code == expected, candidate_size=len(code), relocations=relocations)
            except (ValueError, IndexError) as error:
                record.update(status='relocation_error', error=str(error))
        results.append(record)
    sources = [SOURCE, 'src/recovered/call_leaf_helpers.c', 'analysis/call-helper-specs.json',
               'tools/caller_compiler_fixes.py', 'tools/integer_recovery.py']
    report = dict(family='caller-compiler-fixes', dol_sha256=manifest['dol_sha256'],
                  scope='Full relocated function code; compiler-managed frames, provisional C interfaces',
                  compiler_sha256=digest(cc), runner_sha256=digest(runner),
                  model_hashes={p: digest(ROOT / p) for p in sources},
                  candidate_interface='Recognized 48-byte embedded guards, switch guards, swap-zero and result-flag wrappers; provisional types',
                  checked=len(results), matched=sum(r['exact_match'] for r in results),
                  matched_bytes=sum(r['original_size'] for r in results if r['exact_match']), results=results)
    (output / 'report.json').write_text(json.dumps(report, indent=2) + '\n')
    print(f'{report["matched"]}/{len(results)} exact matches / {report["matched_bytes"]} bytes; '
          f'{dict(collections.Counter(r["status"] for r in results))}')
    if any(r['status'].endswith('_error') for r in results):
        raise SystemExit(1)


if __name__ == '__main__':
    main()
